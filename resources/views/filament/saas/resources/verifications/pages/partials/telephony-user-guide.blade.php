        <span>Calling help</span>
    </summary>

    <div style="padding:12px 2px 2px;font-size:11px;line-height:1.55;color:#475569;">
        <div style="font-weight:850;color:#0f172a;">Before your first call</div>
        <ol style="margin:6px 0 0;padding-left:18px;">
            <li>Connect your headset before opening the phone.</li>
            <li>Allow microphone access when the browser asks.</li>
            <li>In MightyCall phone settings, select the connected microphone and speaker, then confirm the microphone level responds.</li>
        </ol>

        <div style="margin-top:12px;font-weight:850;color:#0f172a;">If calling is not ready</div>
        <ul style="margin:6px 0 0;padding-left:18px;">
            <li><strong>Microphone not detected:</strong> reconnect or enable the device, select it in MightyCall settings, and refresh the page.</li>
            <li><strong>Changed headset:</strong> refresh the page so MightyCall can discover the new device.</li>
            <li><strong>Phone remains off:</strong> confirm the microphone works in Windows and close other calling applications.</li>
            <li><strong>Credential message:</strong> ask your SaaS administrator to verify your WebPhone credential under User Calling Access.</li>
        </ul>

        <div style="margin-top:12px;font-weight:850;color:#0f172a;">During a call</div>
        <p style="margin:6px 0 0;">Use <strong>Phone</strong> to show or hide MightyCall controls. Select <strong>Keyboard</strong> inside MightyCall when you need number-pad tones for an automated insurance menu.</p>
    </div>
</details>
